#!/usr/bin/env bash
# Rebase the fork commits of the current branch onto $REMOTE/$BASE.
#
# The fork renames `clingo` to `clingo_funasp` in the Python stubs and tests
# (see update-pytest.sh). To avoid conflicts there, the rename is stripped from
# every fork commit before rebasing, and regenerated afterwards as a separate
# last commit with the message in $GEN_MSG. That commit is dropped and
# recreated on every run, so never edit it by hand.
#
# Environment:
#   REMOTE  upstream remote name      (default: upstream)
#   BASE    upstream branch to follow (default: wip-20)
#   FETCH   set to 0 to skip fetching (default: 1)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

REMOTE=${REMOTE:-upstream}
BASE=${BASE:-wip-20}
FETCH=${FETCH:-1}
GENERATED=(lib/python-api/stubs lib/python-api/tests)
GEN_MSG="Rename clingo to clingo_funasp in Python stubs and tests (generated by update-pytest.sh)"

BRANCH=$(git symbolic-ref --short HEAD)
if [ -n "$(git status --porcelain --untracked-files=no)" ]; then
    echo "Working tree not clean. Commit or stash your changes first."
    exit 1
fi

if [ "$FETCH" != 0 ]; then
    # Fast-forward only: refuses if the local $BASE has diverged.
    git fetch "$REMOTE" "$BASE:$BASE"
fi

OLD_BASE=$(git merge-base HEAD "$BASE")
if [ "$OLD_BASE" = "$(git rev-parse "$BASE")" ]; then
    echo "Already up to date with $BASE."
    exit 0
fi
if [ -n "$(git rev-list --merges "$OLD_BASE"..HEAD)" ]; then
    echo "The fork commits contain merge commits. Linearize them first."
    exit 1
fi

# Safety check: in files that also exist upstream, the fork's changes under
# ${GENERATED[*]} must be exactly what update-pytest.sh produces. Anything else
# would be lost when the rename is stripped.
git checkout -q "$OLD_BASE" -- "${GENERATED[@]}"
./update-pytest.sh
if ! git diff --quiet HEAD -- "${GENERATED[@]}"; then
    echo "The fork changes these upstream files beyond the rename done by update-pytest.sh:"
    git diff --stat HEAD -- "${GENERATED[@]}"
    echo "Move those changes into fork-only files (e.g. a new test file) first."
    git reset -q --hard HEAD
    exit 1
fi
git reset -q --hard HEAD

BACKUP="backup/$BRANCH/$(date +%Y%m%d-%H%M%S)"
git branch "$BACKUP"
echo "Backup created: $BACKUP"
trap 'echo; echo "Failed. To restore: git rebase --abort 2>/dev/null; git reset --hard $BACKUP"' ERR

# 1. Drop the generated commit left by a previous run.
if [ "$(git log -1 --format=%s)" = "$GEN_MSG" ]; then
    git reset -q --hard HEAD~1
fi
N=$(git rev-list --count "$OLD_BASE"..HEAD)
echo "Rebasing $N fork commit(s) from $(git rev-parse --short "$OLD_BASE") onto $BASE ($(git rev-parse --short "$BASE"))."

# 2. Strip the rename from every fork commit (replayed in place on OLD_BASE).
#    Files that only exist in the fork are left untouched.
git rebase -q --force-rebase "$OLD_BASE" \
    --exec "git checkout -q $OLD_BASE -- ${GENERATED[*]} && git commit -q --amend --no-edit --allow-empty"

# 3. Rebase onto the new base. Commits that end up empty are dropped.
#    On conflict: resolve, `git rebase --continue`, then run
#    `./update-pytest.sh && git add -u -- ${GENERATED[*]} && git commit -m "$GEN_MSG"`.
git rebase --no-keep-empty --empty=drop --onto "$BASE" "$OLD_BASE"
M=$(git rev-list --count "$BASE"..HEAD)
if [ "$M" -ne "$N" ]; then
    echo "Note: $((N - M)) commit(s) became empty and were dropped (already upstream, or rename-only)."
fi

# 4. Regenerate the rename as a separate last commit.
./update-pytest.sh
git add -u -- "${GENERATED[@]}"
if ! git diff --cached --quiet; then
    git commit -q -m "$GEN_MSG"
fi

echo
echo "Done. Review:  git range-diff $OLD_BASE..$BACKUP $BASE..HEAD"
echo "Publish:       git push --force-with-lease origin $BRANCH"
